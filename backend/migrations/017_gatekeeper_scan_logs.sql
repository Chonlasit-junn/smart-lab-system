-- Operator-run only, BEFORE deploying the Gatekeeper access-check Backend.
-- Adds scan history; does not update or remove any existing rows.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE IF NOT EXISTS public.gatekeeper_scan_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id integer REFERENCES public.labs(id) ON DELETE SET NULL,
    lab_code text NOT NULL,
    device_id varchar(128),
    user_id integer REFERENCES public.users(id) ON DELETE SET NULL,
    booking_id bigint REFERENCES public.bookings(id) ON DELETE SET NULL,
    decision varchar(16) NOT NULL,
    reason_code varchar(64) NOT NULL,
    liveness_score double precision,
    face_distance double precision,
    scanned_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT gatekeeper_scan_logs_decision_check
        CHECK (decision IN ('granted', 'denied')),
    CONSTRAINT gatekeeper_scan_logs_liveness_check
        CHECK (liveness_score IS NULL OR (liveness_score >= 0 AND liveness_score <= 1))
);

CREATE INDEX IF NOT EXISTS idx_gatekeeper_scan_logs_lab_id_id
    ON public.gatekeeper_scan_logs (lab_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_gatekeeper_scan_logs_user_id_id
    ON public.gatekeeper_scan_logs (user_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_gatekeeper_scan_logs_device_id_id
    ON public.gatekeeper_scan_logs (device_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_gatekeeper_scan_logs_booking_id
    ON public.gatekeeper_scan_logs (booking_id);
CREATE INDEX IF NOT EXISTS idx_gatekeeper_scan_logs_scanned_at
    ON public.gatekeeper_scan_logs (scanned_at);

-- Access goes through the Backend's Admin authorization. Browser roles cannot
-- read biometric access history directly; no public RLS policy is added.
ALTER TABLE public.gatekeeper_scan_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.gatekeeper_scan_logs FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.gatekeeper_scan_logs_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.gatekeeper_scan_logs FROM anon;
        REVOKE ALL ON SEQUENCE public.gatekeeper_scan_logs_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.gatekeeper_scan_logs FROM authenticated;
        REVOKE ALL ON SEQUENCE public.gatekeeper_scan_logs_id_seq FROM authenticated;
    END IF;
END;
$$;
COMMIT;
