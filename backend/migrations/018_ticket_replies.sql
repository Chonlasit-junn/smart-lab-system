-- Operator-run only, BEFORE deploying the Backend that writes ticket replies.
-- Additive: existing tickets and messages are retained unchanged.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE IF NOT EXISTS public.ticket_replies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id integer NOT NULL REFERENCES public.tickets(id) ON DELETE CASCADE,
    admin_id integer REFERENCES public.users(id) ON DELETE SET NULL,
    responder_name varchar(255) NOT NULL,
    message text NOT NULL,
    is_resolved boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ticket_replies_message_check
        CHECK (length(btrim(message)) BETWEEN 1 AND 5000)
);

CREATE INDEX IF NOT EXISTS idx_ticket_replies_ticket_id_id
    ON public.ticket_replies (ticket_id, id);

ALTER TABLE public.ticket_replies ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ticket_replies FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.ticket_replies_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON public.ticket_replies FROM anon;
        REVOKE ALL ON SEQUENCE public.ticket_replies_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON public.ticket_replies FROM authenticated;
        REVOKE ALL ON SEQUENCE public.ticket_replies_id_seq FROM authenticated;
    END IF;
END;
$$;
COMMIT;
